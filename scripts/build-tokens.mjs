import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function resolveToken(name, registry, trail = []) {
  if (trail.includes(name))
    throw new Error(`Token alias cycle: ${[...trail, name].join(" → ")}`);
  const token = registry[name];
  if (!token) throw new Error(`Unknown token: ${name}`);
  return typeof token.value === "string"
    ? token.value.replace(/\{([\w-]+)\}/g, (_, ref) =>
        String(resolveToken(ref, registry, [...trail, name])),
      )
    : token.value;
}
const cssValue = (value) => String(value).replace(/\{([\w-]+)\}/g, "var(--$1)");
function declarations(tokens) {
  return Object.entries(tokens)
    .map(([name, token]) => `  --${name}: ${cssValue(token.value)};`)
    .join("\n");
}
export function contrastRatio(a, b) {
  const luminance = (hex) => {
    if (!/^#[\da-f]{6}$/i.test(hex))
      throw new Error(`Expected opaque hex color: ${hex}`);
    const rgb = [1, 3, 5]
      .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
      .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
    return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722;
  };
  const x = luminance(a),
    y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
export function compileTokens(source) {
  const names = Object.keys(source.semantic.light);
  if (
    names.slice().sort().join() !==
    Object.keys(source.semantic.dark).sort().join()
  )
    throw new Error("Light and dark semantic names differ");
  const catalog = [],
    profiles = {},
    contrast = [];
  for (const theme of ["light", "dark"]) {
    for (const density of ["comfortable", "compact"]) {
      const registry = {
        ...source.primitive,
        ...source.semantic[theme],
        ...source.density[density],
        ...source.component,
      };
      const resolved = Object.fromEntries(
        Object.keys(registry).map((name) => [
          name,
          resolveToken(name, registry),
        ]),
      );
      profiles[`${theme}-${density}`] = {
        name: source.name,
        version: source.version,
        theme,
        density,
        tokens: resolved,
      };
    }
    const tokens = profiles[`${theme}-comfortable`].tokens;
    for (const [label, text, bg] of [
      ["Nội dung chính", "foreground", "surface"],
      ["Nội dung phụ", "foreground-muted", "surface"],
      ["Nút chính", "action-foreground", "action"],
      ["Thành công", "success", "success-soft"],
      ["Cảnh báo", "warning", "warning-soft"],
      ["Lỗi", "danger", "danger-soft"],
      ["Thông tin", "info", "info-soft"],
    ]) {
      contrast.push({
        theme,
        label,
        text,
        bg,
        foreground: tokens[text],
        background: tokens[bg],
        ratio: Number(contrastRatio(tokens[text], tokens[bg]).toFixed(2)),
      });
    }
  }
  for (const layer of ["primitive", "semantic", "component", "density"]) {
    const group =
      layer === "semantic"
        ? source.semantic.light
        : layer === "density"
          ? source.density.comfortable
          : source[layer];
    for (const [name, token] of Object.entries(group))
      catalog.push({
        name,
        layer,
        ...token,
        light: profiles["light-comfortable"].tokens[name],
        dark: profiles["dark-comfortable"].tokens[name],
        compact: profiles["light-compact"].tokens[name],
      });
  }
  for (const value of Object.values(source.tailwind))
    for (const [, ref] of String(value).matchAll(/\{([\w-]+)\}/g))
      resolveToken(ref, {
        ...source.primitive,
        ...source.semantic.light,
        ...source.density.comfortable,
        ...source.component,
      });
  const css = `/* Generated by npm run tokens:build. Edit tokens/source.json. */\n:root {\n  color-scheme: light;\n${declarations(source.primitive)}\n${declarations(source.semantic.light)}\n${declarations(source.density.comfortable)}\n${declarations(source.component)}\n}\n[data-theme="dark"] {\n  color-scheme: dark;\n${declarations(source.semantic.dark)}\n}\n[data-density="compact"] {\n${declarations(source.density.compact)}\n}\n@media (prefers-reduced-motion: reduce) {\n  :root { --duration-fast: 0ms; --duration-normal: 0ms; --duration-slow: 0ms; }\n}\n`;
  const tailwind = `/* Generated by npm run tokens:build. */\n@theme inline {\n${Object.entries(
    source.tailwind,
  )
    .map(([key, value]) => `  --${key}: ${cssValue(value)};`)
    .join(
      "\n",
    )}\n  @keyframes enter { from { opacity:0; transform:translateY(4px) scale(.98); } to { opacity:1; transform:translateY(0) scale(1); } }\n}\n`;
  return { catalog, profiles, contrast, css, tailwind };
}
export async function buildTokens(check = false) {
  const source = JSON.parse(
    await readFile(path.join(root, "tokens/source.json"), "utf8"),
  );
  const result = compileTokens(source);
  const json = (value) => JSON.stringify(value, null, 2) + "\n";
  const files = {
    "apps/web/src/core/ui/styles/tokens.css": result.css,
    "apps/web/src/core/ui/styles/token-theme.css": result.tailwind,
    "apps/web/src/core/ui/design-system/schema/token-data.json": json({
      name: source.name,
      version: source.version,
      catalog: result.catalog,
      profiles: result.profiles,
      contrast: result.contrast,
    }),
    "apps/web/public/tokens/oneops.tokens.json": json(source),
    "apps/web/public/tokens/oneops.css": result.css,
    "apps/web/public/tokens/oneops.tailwind.css": result.tailwind,
  };
  for (const [profile, data] of Object.entries(result.profiles))
    files[`apps/web/public/tokens/${profile}.json`] = json(data);
  const differences = [];
  for (const [relative, contents] of Object.entries(files)) {
    const target = path.join(root, relative);
    if (check) {
      let existing = "";
      try {
        existing = await readFile(target, "utf8");
      } catch {}
      if (existing !== contents) differences.push(relative);
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, contents);
    }
  }
  if (differences.length)
    throw new Error(
      `Generated tokens are stale: ${differences.join(", ")}. Run npm run tokens:build.`,
    );
  return {
    count: result.catalog.length,
    files: Object.keys(files).length,
    contrast: result.contrast,
  };
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const result = await buildTokens(process.argv.includes("--check"));
    console.log(
      `${process.argv.includes("--check") ? "Verified" : "Generated"} ${result.count} tokens across ${result.files} files.`,
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
